#!/usr/bin/env node
/**
 * Generate the initial Supabase seed SQL and Storage upload manifest from G.json.
 * Run from the project root: node scripts/migrate-data.mjs
 * This script never connects to Supabase or uploads files.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'src', 'data', 'G.json');
const outputSql = path.join(root, 'migrations', 'seed.generated.sql');
const outputManifest = path.join(root, 'migrations', 'media-manifest.json');
const data = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

const quote = (value) => value === null || value === undefined
  ? 'NULL'
  : `'${String(value).replaceAll("'", "''")}'`;
const jsonb = (value) => `${quote(JSON.stringify(value ?? null))}::jsonb`;
const storageReference = (value) => {
  if (typeof value !== 'string' || !value.startsWith('/assets/')) return value ?? null;
  const relative = value.replace(/^\/assets\//, '');
  const parts = relative.split('/');
  if (parts[0] === 'profil') return `storage://anggota/${parts.at(-1)}`;
  if (parts[0] === 'kenangan') return `storage://galeri/${parts.at(-1)}`;
  if (parts[0] === 'audio') return `storage://assets-global/audio/${parts.at(-1)}`;
  if (parts[0] === 'logo') return `storage://assets-global/logo/${parts.at(-1)}`;
  return value;
};
const replaceStorageReferences = (value) => {
  if (Array.isArray(value)) return value.map(replaceStorageReferences);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, replaceStorageReferences(item)]));
  return storageReference(value);
};
const number = (value, fallback = 0) => Number.isFinite(Number(value)) ? Number(value) : fallback;
const rowsSql = (rows, columns, conflict, updates) => {
  if (!rows.length) return '-- Tidak ada data untuk tabel ini.\n';
  const values = rows.map((row) => `(${columns.map((column) => column.sql(row)).join(', ')})`).join(',\n');
  return `insert into public.${columns.table} (${columns.names.join(', ')})\nvalues\n${values}\non conflict (${conflict}) do update set ${updates};\n`;
};

const siteSettings = replaceStorageReferences({ ...data });
for (const key of ['namaSiswa', 'strukturOrg', 'guru', 'skills', 'galeri']) delete siteSettings[key];
siteSettings.media = {
  ...(siteSettings.media || {}),
  logo_url: storageReference('/assets/logo/logo-utama.svg'),
  audio_url: storageReference('/assets/audio/videoplayback.weba'),
};

const roleByName = new Map((data.strukturOrg || []).map((item) => [item.nama, item]));
const memberRows = (data.namaSiswa || []).map((member, index) => {
  const role = roleByName.get(member.nama);
  return {
    nis: String(member.nis || '').trim(),
    nama: member.nama,
    kelas: member.kelas || data.namaKelas || 'XI-9',
    jabatan: role?.jabatan || member.jabatan || null,
    deskripsi: member.desc || member.deskripsi || null,
    foto_url: storageReference(member.foto || role?.foto || null),
    audio_url: storageReference(member.audio || null),
    audio_nama: member.namaAudio || member.nama || null,
    foto_audio_url: storageReference(member.fotoAudio || member.foto || null),
    deskripsi_audio: member.descAudio || member.desc || null,
    social: member.social || {},
    urutan: index,
  };
}).filter((row) => row.nis && row.nama);

const teacherRows = (data.guru || []).map((item, index) => ({ ...item, urutan: index }));
const skillRows = (data.skills || []).map((item, index) => ({ ...item, urutan: index }));
const galleryRows = (data.galeri || []).map((item, index) => ({
  src: storageReference(item.src),
  caption: item.caption || item.label || '',
  urutan: index,
})).filter((item) => item.src);

let sql = `-- Generated by scripts/migrate-data.mjs on ${new Date().toISOString()}\n-- Review this file before running it in Supabase SQL Editor.\nbegin;\n\n`;
sql += `insert into public.site_settings (key, value, updated_at) values ('site', ${jsonb(siteSettings)}, now())\non conflict (key) do update set value = excluded.value, updated_at = now();\n\n`;

if (memberRows.length) {
  const values = memberRows.map((r) => `(${[
    quote(r.nis), quote(r.nama), quote(r.kelas), quote(r.jabatan), quote(r.deskripsi), quote(r.foto_url),
    quote(r.audio_url), quote(r.audio_nama), quote(r.foto_audio_url), quote(r.deskripsi_audio), jsonb(r.social), number(r.urutan),
  ].join(', ')})`).join(',\n');
  sql += `insert into public.anggota (nis, nama, kelas, jabatan, deskripsi, foto_url, audio_url, audio_nama, foto_audio_url, deskripsi_audio, social, urutan)\nvalues\n${values}\non conflict (nis) do update set nama=excluded.nama, kelas=excluded.kelas, jabatan=excluded.jabatan, deskripsi=excluded.deskripsi, foto_url=excluded.foto_url, audio_url=excluded.audio_url, audio_nama=excluded.audio_nama, foto_audio_url=excluded.foto_audio_url, deskripsi_audio=excluded.deskripsi_audio, social=excluded.social, urutan=excluded.urutan, updated_at=now();\n\n`;
}

if (teacherRows.length) {
  const values = teacherRows.map((r) => `(${[quote(r.nama), quote(r.mapel), quote(r.peran), quote(r.quote), jsonb(r.expertise || []), number(r.urutan)].join(', ')})`).join(',\n');
  sql += `insert into public.guru (nama, mapel, peran, quote, expertise, urutan)\nvalues\n${values}\non conflict (nama) do update set mapel=excluded.mapel, peran=excluded.peran, quote=excluded.quote, expertise=excluded.expertise, urutan=excluded.urutan, updated_at=now();\n\n`;
}

if (skillRows.length) {
  const values = skillRows.map((r) => `(${[quote(r.nama), number(r.level), quote(r.icon), quote(r.desc || r.deskripsi), number(r.urutan)].join(', ')})`).join(',\n');
  sql += `insert into public.skills (nama, level, icon, deskripsi, urutan)\nvalues\n${values}\non conflict (nama) do update set level=excluded.level, icon=excluded.icon, deskripsi=excluded.deskripsi, urutan=excluded.urutan, updated_at=now();\n\n`;
}

if (galleryRows.length) {
  const values = galleryRows.map((r) => `(${[quote(r.src), quote(r.caption), number(r.urutan)].join(', ')})`).join(',\n');
  sql += `insert into public.galeri (src, caption, urutan)\nvalues\n${values}\non conflict (src) do update set caption=excluded.caption, urutan=excluded.urutan, updated_at=now();\n\n`;
}
sql += 'commit;\n';
fs.mkdirSync(path.dirname(outputSql), { recursive: true });
fs.writeFileSync(outputSql, sql, 'utf8');

// Collect media literals from the canonical data source and remaining public/source files.
// The retired duplicate config is documented in docs/AUDIT.md, not re-imported into the seed.
const extensionPattern = /\.(?:svg|png|jpe?g|webp|gif|mp3|wav|ogg|m4a|weba|mp4|webm)$/i;
const mediaReferences = new Map();
const scanRoots = ['src', 'public'];
const scanFile = (filePath) => {
  if (!/\.(?:astro|js|mjs|json|html|xml)$/i.test(filePath)) return;
  const body = fs.readFileSync(filePath, 'utf8');
  const regex = /(?:\/assets\/|(?:\.\.\/)+assets\/|\.\/assets\/)([A-Za-z0-9._/-]+\.(?:svg|png|jpe?g|webp|gif|mp3|wav|ogg|m4a|weba|mp4|webm))/gi;
  for (const match of body.matchAll(regex)) {
    const relativeAsset = `assets/${match[1]}`.replaceAll('\\', '/');
    const record = mediaReferences.get(relativeAsset) || { path: relativeAsset, referencedIn: [] };
    const relativeSource = path.relative(root, filePath).replaceAll(path.sep, '/');
    if (!record.referencedIn.includes(relativeSource)) record.referencedIn.push(relativeSource);
    mediaReferences.set(relativeAsset, record);
  }
};
const walk = (directory) => {
  if (!fs.existsSync(directory)) return;
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (entry.isFile()) scanFile(full);
  }
};
for (const dir of scanRoots) walk(path.join(root, dir));

const manifest = [...mediaReferences.values()].map((record) => {
  const sourcePath = path.posix.join('public', record.path);
  const absoluteSource = path.join(root, sourcePath);
  const parts = record.path.split('/');
  let targetPath;
  if (parts[1] === 'logo') targetPath = `assets-global/logo/${parts.at(-1)}`;
  else if (parts[1] === 'audio') targetPath = `assets-global/audio/${parts.at(-1)}`;
  else if (parts[1] === 'kenangan') targetPath = `galeri/${parts.at(-1)}`;
  else if (parts[1] === 'profil') targetPath = `anggota/${parts.at(-1)}`;
  else targetPath = `assets-global/${parts.slice(1).join('/')}`;
  return {
    source: sourcePath,
    targetBucket: process.env.SUPABASE_STORAGE_BUCKET || 'astro',
    targetPath,
    existsInArchive: fs.existsSync(absoluteSource),
    status: fs.existsSync(absoluteSource) ? 'ready-to-upload' : 'source-file-missing-from-zip',
    referencedIn: record.referencedIn.sort(),
  };
}).sort((a, b) => a.targetPath.localeCompare(b.targetPath));

const manifestDocument = {
  generatedAt: new Date().toISOString(),
  sourceOfStructuredData: 'src/data/G.json',
  note: 'This manifest is a manual upload checklist. The script does not upload files or connect to Supabase. SQL rows use storage:// references that the server data layer resolves into public Storage URLs.',
  summary: {
    anggota: memberRows.length,
    guru: teacherRows.length,
    skills: skillRows.length,
    galeri: galleryRows.length,
    mediaReferences: manifest.length,
    mediaFilesPresent: manifest.filter((item) => item.existsInArchive).length,
    mediaFilesMissing: manifest.filter((item) => !item.existsInArchive).length,
  },
  files: manifest,
};
fs.writeFileSync(outputManifest, `${JSON.stringify(manifestDocument, null, 2)}\n`, 'utf8');

console.log(`Seed SQL: ${path.relative(root, outputSql)}`);
console.log(`Media manifest: ${path.relative(root, outputManifest)}`);
console.log(`Rows: ${memberRows.length} anggota, ${teacherRows.length} guru, ${skillRows.length} skills, ${galleryRows.length} galeri`);
console.log(`Media: ${manifestDocument.summary.mediaFilesPresent} ada, ${manifestDocument.summary.mediaFilesMissing} belum ada di arsip`);
